CREATE OR REPLACE FORCE EDITIONABLE VIEW "FBOOK"."V_MATCHING_RATES" ("SEARCH_PK_ID", "RATE_PK_ID") AS 
  SELECT PK_ID AS SEARCH_PK_ID, RATE_PK_ID FROM RATE_SEARCH_LOG S
JOIN V_RATE_MST R ON 
S.ORIGIN_PORT_ID = R.RATE_FROM_PORT AND S.DESTINATION_PORT_ID = R.RATE_TO_PORT
AND S.SEARCH_TYPE = R.FCL_LCL_FLAG AND NVL(S.CONT_TYPE,0) = NVL(R.FCL_CONTAINER_TYPE,0);